def table(headers, rows, widths):
    t=doc.add_table(rows=1,cols=len(headers))
    t.alignment=WD_TABLE_ALIGNMENT.CENTER;t.autofit=False
    pr=t._tbl.tblPr
    borders=OxmlElement("w:tblBorders")
    for edge in ["top","left","bottom","right","insideH","insideV"]:
        b=OxmlElement("w:"+edge)
        for k,v in {"val":"single","sz":"4","color":"D9D9D9"}.items():b.set(qn("w:"+k),v)
        borders.append(b)
    pr.append(borders)
    for i,w in enumerate(widths):
        t.columns[i].width=Inches(w)
    for index,row in enumerate([headers]+rows):
        cells=t.rows[0].cells if index==0 else t.add_row().cells
        trPr=cells[0]._tc.getparent().get_or_add_trPr()
        cant=OxmlElement("w:cantSplit");trPr.append(cant)
        if index==0:
            repeat=OxmlElement("w:tblHeader");trPr.append(repeat)
        for col,text in enumerate(row):
            c=cells[col];c.width=Inches(widths[col]);c.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            tcPr=c._tc.get_or_add_tcPr();marg=OxmlElement("w:tcMar")
            for e in ["top","bottom","left","right"]:
                x=OxmlElement("w:"+e);x.set(qn("w:w"),"85");x.set(qn("w:type"),"dxa");marg.append(x)
            tcPr.append(marg)
            shade=OxmlElement("w:shd");shade.set(qn("w:fill"),"DDE9F3" if index==0 else "FFFFFF");tcPr.append(shade)
            p=c.paragraphs[0];p.paragraph_format.space_after=Pt(1);p.paragraph_format.space_before=Pt(1);p.paragraph_format.line_spacing=Pt(15)
            rr=p.add_run(text);rr.font.name=FONT;rr.font.size=Pt(10.4);rr.bold=index==0
    doc.add_paragraph().paragraph_format.space_after=Pt(0)
    return t

