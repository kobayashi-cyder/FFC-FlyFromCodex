def para(text, bold_lead=None):
    p=doc.add_paragraph()
    if bold_lead and text.startswith(bold_lead):
        p.add_run(bold_lead).bold=True;p.add_run(text[len(bold_lead):])
    else:p.add_run(text)
    return p

